"""Embed the web app icons as C arrays: embed_assets.py <out.h> <name=file.png> ..."""
import sys
from pathlib import Path

out = ["/* Auto-generated by scripts/embed_assets.py - do not edit. */"]
for arg in sys.argv[2:]:
    name, path = arg.split("=", 1)
    data = Path(path).read_bytes()
    out.append("static const unsigned char %s[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 16):
        out.append("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    out.append("};")
Path(sys.argv[1]).write_text("\n".join(out) + "\n", encoding="utf-8")
